//! Tests `Builder`: generating to a path, errors, and `generate()` run the way
//! a build script runs it.
//!
//! `generate()` reads `OUT_DIR` and prints to stdout, so it runs in a child:
//! `child_generate` re-runs this binary with `OUT_DIR` set or removed.

use imping_build::{Builder, Error};
use std::path::{Path, PathBuf};
use std::process::Command;

fn fixture() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/small.json")
}

/// Returns an empty scratch directory for one test.
fn scratch(name: &str) -> PathBuf {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR"))
        .join("imping-build")
        .join(name);
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("create scratch directory");
    dir
}

#[test]
fn generate_to_writes_bindings_with_a_source_line_and_returns_warnings() {
    let out = scratch("generate_to").join("bindings.rs");
    let warnings = Builder::new(fixture()).generate_to(&out).expect("generate");

    let text = std::fs::read_to_string(&out).expect("read output");
    let mut lines = text.lines();
    assert!(
        lines
            .next()
            .unwrap()
            .starts_with("// Generated by imping-codegen ")
    );
    assert_eq!(
        lines.next().unwrap(),
        format!("// Source: {}", fixture().display())
    );
    assert!(text.contains("pub mod game {"));
    assert!(text.contains("pub mod math {"));

    let warnings: Vec<String> = warnings.iter().map(ToString::to_string).collect();
    assert_eq!(
        warnings,
        ["`game.exe` vtable `Entity` skipped; vtables are not supported yet"]
    );
}

#[test]
fn module_names_reach_the_generator() {
    let out = scratch("module_name").join("bindings.rs");
    Builder::new(fixture())
        .module_name("game.exe", "old_game")
        .generate_to(&out)
        .expect("generate");
    let text = std::fs::read_to_string(&out).expect("read output");
    assert!(text.contains("pub mod old_game {"));
    assert!(!text.contains("pub mod game {"));
}

#[test]
fn accepted_builds_reach_the_generator() {
    let out = scratch("accept_build").join("bindings.rs");
    Builder::new(fixture())
        .accept_build("game.exe", 0x64b8f2a1, 0xa3c000)
        .generate_to(&out)
        .expect("generate");
    let text = std::fs::read_to_string(&out).expect("read output");
    assert!(text.contains("image_size: 0xa2b000"), "the IR's build");
    assert!(text.contains("image_size: 0xa3c000"), "the extra build");
}

#[test]
fn errors_name_the_file_involved() {
    let dir = scratch("errors");
    let out = dir.join("bindings.rs");

    let missing = dir.join("missing.json");
    let error = Builder::new(&missing).generate_to(&out).unwrap_err();
    assert!(matches!(&error, Error::Read { path, .. } if path == &missing));
    assert!(
        error
            .to_string()
            .starts_with(&format!("failed to read IR file `{}`: ", missing.display())),
        "{error}"
    );

    let invalid = dir.join("invalid.json");
    std::fs::write(&invalid, "{ \"format_version\": ").expect("write invalid IR");
    let error = Builder::new(&invalid).generate_to(&out).unwrap_err();
    assert!(matches!(&error, Error::Parse { path, .. } if path == &invalid));
    let message = error.to_string();
    assert!(
        message.starts_with(&format!("`{}` is not a valid IR file: ", invalid.display())),
        "{message}"
    );
    assert!(
        message.contains("line 1"),
        "the JSON position is included: {message}"
    );

    let error = Builder::new(fixture())
        .module_name("other.dll", "other")
        .generate_to(&out)
        .unwrap_err();
    assert!(matches!(
        &error,
        Error::Generate {
            source: imping_codegen::Error::UnknownModule { .. },
            ..
        }
    ));
    assert_eq!(
        error.to_string(),
        format!(
            "failed to generate bindings from `{}`: `module_name` names `other.dll`, which is not in the IR",
            fixture().display()
        )
    );

    let unwritable = dir.join("no-such-dir").join("bindings.rs");
    let error = Builder::new(fixture())
        .generate_to(&unwritable)
        .unwrap_err();
    assert!(matches!(&error, Error::Write { path, .. } if path == &unwritable));
    assert!(
        error
            .to_string()
            .starts_with(&format!("failed to write `{}`: ", unwritable.display())),
        "{error}"
    );
}

/// Set in the child process to the scenario it should run.
const CHILD: &str = "IMPING_BUILD_TEST_CHILD";

/// Runs `generate()` when this binary is re-run as a child, and nothing in a
/// normal test run.
#[test]
fn child_generate() {
    let Some(scenario) = std::env::var_os(CHILD) else {
        return;
    };
    let mut builder = Builder::new(fixture());
    if scenario == "out_file" {
        builder = builder.out_file("game.rs");
    }
    match builder.generate() {
        Ok(()) => println!("child: ok"),
        Err(error) => println!("child: error: {error}"),
    }
}

/// Re-runs `child_generate` with `scenario` and the given `OUT_DIR`, and
/// returns its stdout.
fn run_child(scenario: &str, out_dir: Option<&Path>) -> String {
    let mut command = Command::new(std::env::current_exe().expect("current exe"));
    command
        .args([
            "--exact",
            "child_generate",
            "--nocapture",
            "--test-threads=1",
        ])
        .env(CHILD, scenario);
    match out_dir {
        Some(dir) => command.env("OUT_DIR", dir),
        None => command.env_remove("OUT_DIR"),
    };
    let output = command.output().expect("run child");
    assert!(output.status.success(), "child failed: {output:?}");
    String::from_utf8(output.stdout).expect("UTF-8 output")
}

#[test]
fn generate_writes_to_out_dir_and_prints_cargo_lines() {
    let dir = scratch("out_dir");
    let stdout = run_child("default", Some(&dir));
    assert!(stdout.contains("child: ok"), "{stdout}");
    assert!(
        stdout.contains(&format!("cargo:rerun-if-changed={}\n", fixture().display())),
        "{stdout}"
    );
    assert!(
        stdout.contains(
            "cargo:warning=imping: `game.exe` vtable `Entity` skipped; vtables are not supported yet\n"
        ),
        "{stdout}"
    );
    let text = std::fs::read_to_string(dir.join("imped.rs")).expect("imped.rs is written");
    assert!(text.contains("pub mod game {"));
}

#[test]
fn out_file_renames_the_generated_file() {
    let dir = scratch("out_file");
    let stdout = run_child("out_file", Some(&dir));
    assert!(stdout.contains("child: ok"), "{stdout}");
    assert!(dir.join("game.rs").exists());
    assert!(!dir.join("imped.rs").exists());
}

#[test]
fn generate_needs_out_dir() {
    let stdout = run_child("default", None);
    assert!(
        stdout.contains(
            "child: error: OUT_DIR is not set; `generate()` is for build.rs, use `generate_to(path)` elsewhere"
        ),
        "{stdout}"
    );
}
