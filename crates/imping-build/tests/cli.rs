//! Tests the `imping` command-line tool, run as a separate process.

#![cfg(feature = "cli")]

use std::path::{Path, PathBuf};
use std::process::{Command, Output};

fn imping(args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_imping"))
        .args(args)
        .output()
        .expect("run imping")
}

fn fixture() -> String {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/small.json")
        .display()
        .to_string()
}

fn scratch(name: &str) -> PathBuf {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR"))
        .join("imping-cli")
        .join(name);
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("create scratch directory");
    dir
}

fn text(bytes: &[u8]) -> String {
    String::from_utf8(bytes.to_vec()).expect("UTF-8 output")
}

const VTABLE_WARNING: &str =
    "warning: `game.exe` vtable `Entity` skipped; vtables are not supported yet";

#[test]
fn generate_writes_to_standard_output_and_warns_on_standard_error() {
    let output = imping(&["generate", &fixture()]);
    assert!(output.status.success(), "{output:?}");
    let stdout = text(&output.stdout);
    assert!(
        stdout.starts_with("// Generated by imping-codegen "),
        "{stdout}"
    );
    assert!(stdout.contains(&format!("// Source: {}", fixture())));
    assert!(stdout.contains("pub mod game {"));
    assert!(text(&output.stderr).contains(VTABLE_WARNING));
}

#[test]
fn generate_writes_a_file_with_renamed_modules() {
    let out = scratch("generate").join("imped.rs");
    let output = imping(&[
        "generate",
        &fixture(),
        "-o",
        &out.display().to_string(),
        "--module-name",
        "game.exe=old_game",
    ]);
    assert!(output.status.success(), "{output:?}");
    assert!(output.stdout.is_empty());
    assert!(text(&output.stderr).contains(VTABLE_WARNING));
    let written = std::fs::read_to_string(&out).expect("output file");
    assert!(written.contains("pub mod old_game {"));
}

#[test]
fn check_prints_warnings_and_a_summary() {
    let output = imping(&["check", &fixture()]);
    assert!(output.status.success(), "{output:?}");
    assert!(text(&output.stderr).contains(VTABLE_WARNING));
    assert_eq!(
        text(&output.stdout),
        format!("`{}` generates bindings (1 warning)\n", fixture())
    );
}

#[test]
fn errors_exit_with_1() {
    let missing = scratch("errors").join("missing.json").display().to_string();
    let output = imping(&["check", &missing]);
    assert_eq!(output.status.code(), Some(1));
    assert!(
        text(&output.stderr).starts_with(&format!("error: failed to read IR file `{missing}`: ")),
        "{output:?}"
    );

    let output = imping(&["check", &fixture(), "--module-name", "other.dll=other"]);
    assert_eq!(output.status.code(), Some(1));
    assert!(
        text(&output.stderr).contains("`module_name` names `other.dll`, which is not in the IR")
    );
}

#[test]
fn generate_accepts_extra_builds_in_hex_or_decimal() {
    let output = imping(&[
        "generate",
        &fixture(),
        "--accept-build",
        "game.exe=0x64b8f2a1:0xa3c000",
        "--accept-build",
        "game.exe=1:4096",
    ]);
    assert!(output.status.success(), "{output:?}");
    let source = text(&output.stdout);
    assert!(source.contains("image_size: 0xa3c000"));
    assert!(source.contains("timestamp: 0x1,"));
    assert!(source.contains("image_size: 0x1000"));
}

#[test]
fn usage_errors_exit_with_1() {
    let output = imping(&["generate", &fixture(), "--module-name", "no-equals-sign"]);
    assert_eq!(output.status.code(), Some(1));
    assert!(text(&output.stderr).contains("expected `<IR module>=<Rust module>`"));

    let output = imping(&[
        "generate",
        &fixture(),
        "--accept-build",
        "game.exe=0x64b8f2a1",
    ]);
    assert_eq!(output.status.code(), Some(1));
    assert!(text(&output.stderr).contains("expected `<IR module>=<timestamp>:<image size>`"));

    let output = imping(&["frobnicate"]);
    assert_eq!(output.status.code(), Some(1));
}

#[test]
fn help_and_version_succeed() {
    let output = imping(&["--version"]);
    assert!(output.status.success());
    assert_eq!(
        text(&output.stdout),
        format!("imping {}\n", env!("CARGO_PKG_VERSION"))
    );

    let output = imping(&["--help"]);
    assert!(output.status.success());
    assert!(text(&output.stdout).contains("generate"));
}
